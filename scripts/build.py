#!/usr/bin/env python3
"""Generate self-contained host packages from shared dev-team sources."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def json_file(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def outputs(root: Path) -> dict[str, str]:
    source = root / "shared/dev-team"
    meta = tomllib.loads((source / "plugin.toml").read_text())
    result: dict[str, str] = {}
    base = "plugins/dev-team"
    identity = {key: meta[key] for key in ("name", "version", "description")}
    # No "version" for Claude: a pinned manifest version keeps installs on the cached
    # copy until the string changes. Without one (and none in the marketplace entry),
    # Claude Code versions the plugin by commit SHA, so every push is an update.
    claude_identity = {key: value for key, value in identity.items() if key != "version"}
    result[f"{base}/claude/.claude-plugin/plugin.json"] = json_file(
        {**claude_identity, "author": {"name": "j3ko"}}
    )
    result[f"{base}/codex/plugin.json"] = json_file(
        {"$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json", **identity}
    )
    result[f"{base}/codex/.codex-plugin/plugin.json"] = json_file(
        {**identity, "skills": "./skills/"}
    )
    for host in ("claude", "codex"):
        adapter = tomllib.loads((root / f"adapters/{host}.toml").read_text())
        if set(adapter["roles"]) != set(meta["roles"]):
            raise ValueError(f"{host}: adapter and shared roles differ")
        for name, role in meta["roles"].items():
            prompt = (source / f"roles/{name}.md").read_text()
            settings = adapter["roles"][name]
            if host == "claude":
                header = {"name": name, "description": role["description"], **settings}
                fields = "\n".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in header.items())
                result[f"{base}/claude/agents/{name}.md"] = f"---\n{fields}\n---\n\n{prompt}"
            else:
                fields = {
                    "name": f"dev-team-{name}",
                    "description": role["description"],
                    **settings,
                    "developer_instructions": prompt,
                }
                text = "# Generated by scripts/build.py; edit shared/ and adapters/ instead.\n"
                text += "\n".join(f"{key} = {json.dumps(value, ensure_ascii=False)}" for key, value in fields.items()) + "\n"
                # Parse what we emit, including escaped Markdown and Unicode.
                if tomllib.loads(text)["developer_instructions"] != prompt:
                    raise ValueError(f"{name}: instruction serialization changed content")
                result[f"{base}/codex/agents/dev-team-{name}.toml"] = text
        for path in sorted((source / "skills").rglob("*")):
            if path.is_symlink():
                raise ValueError(f"Shared skill sources must be regular files: {path}")
            if path.is_file():
                result[f"{base}/{host}/skills/{path.relative_to(source / 'skills')}"] = path.read_text()
    result[".claude-plugin/marketplace.json"] = json_file({
        "name": "j3ko-agents", "owner": {"name": "j3ko"},
        "description": "Shared development workflows with Claude Code and Codex adapters.",
        "plugins": [{"name": "dev-team", "source": "./plugins/dev-team/claude", "description": meta["description"]}],
    })
    result[".agents/plugins/marketplace.json"] = json_file({
        "name": "j3ko-agents", "interface": {"displayName": "j3ko Agent Plugins"},
        "plugins": [{
            "name": "dev-team",
            "source": {"source": "local", "path": "./plugins/dev-team/codex"},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
            "category": "Productivity",
        }],
    })
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report generated drift without writing")
    args = parser.parse_args()
    expected = outputs(ROOT)
    extra = {
        str(p.relative_to(ROOT)) for p in (ROOT / "plugins/dev-team").rglob("*")
        if p.is_file() or p.is_symlink()
    } - expected.keys()
    if extra:
        print("Unexpected files in generated packages; inspect and remove obsolete files:", file=sys.stderr)
        print("\n".join(sorted(extra)), file=sys.stderr)
        return 1
    for name in expected:
        target = ROOT / name
        if any(p.is_symlink() for p in (target, *target.parents) if p != ROOT and ROOT in p.parents):
            print(f"Refusing generated symlink destination: {target}", file=sys.stderr)
            return 1
    stale = [name for name, body in expected.items() if not (ROOT / name).is_file() or (ROOT / name).is_symlink() or (ROOT / name).read_text() != body]
    if args.check:
        if stale:
            print("Generated files need rebuilding:\n" + "\n".join(stale), file=sys.stderr)
            return 1
        print(f"Checked {len(expected)} generated files.")
        return 0
    for name in stale:
        path = ROOT / name
        if path.is_symlink():
            raise ValueError(f"Refusing to write through generated symlink: {path}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected[name])
    print(f"Generated {len(expected)} files ({len(stale)} changed).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
